/** ดีขึ้น/แย่ลงจาก % เปลี่ยน — ตัวเดียวใช้ทุกหน้า · เปลี่ยนน้อยกว่า 5% = "ทรงตัว" (สีจาง)
    ตรวจรอบ 28 ก.ย.: "ความถี่ ▲1.72% แย่ลง" เปลี่ยนนิดเดียวก็ขึ้นแย่ลง ทำให้หน้ารกและคนตกใจเกินเหตุ
    sense: "higher" ยิ่งมากยิ่งดี · "lower" ยิ่งน้อยยิ่งดี (CPL · %Ads · ความถี่) · "neutral" ไม่บอกดี/แย่ */
export const STEADY_PCT = 5;
export function trendOf(d, sense = "higher") {
  if (d == null || !Number.isFinite(d) || sense === "neutral") return { good: null, word: "" };
  if (Math.abs(d) < STEADY_PCT) return { good: null, word: "ทรงตัว" };
  const good = sense === "lower" ? d < 0 : d > 0;
  return { good, word: good ? "ดีขึ้น" : "แย่ลง" };
}
